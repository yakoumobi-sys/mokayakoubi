const assert = require('node:assert/strict')
const ts = require('typescript')
const fs = require('node:fs')
const path = require('node:path')
const os = require('node:os')
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'moka-test-'))
for (const name of ['config/funnel','lib/leads-validation']) {
  const target = path.join(root, name + '.js')
  fs.mkdirSync(path.dirname(target), {recursive:true})
  fs.writeFileSync(target, ts.transpileModule(fs.readFileSync(name + '.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText)
}
const {funnel,recommendation} = require(path.join(root,'config/funnel.js'))
const {validateLead} = require(path.join(root,'lib/leads-validation.js'))
function valid(track) { return {requestId:'b4f62af1-7c86-4c24-a516-0d5e7caa7521', track, answers:Object.fromEntries(funnel[track].questions.map(q=>[q.key,q.options[0]])),name:'Test QA',phone:'0550000000',email:'',channel:'Téléphone',details:'',date:'',consent:true,website:''} }
for (const track of ['marque','equipe','studio']) assert.equal(validateLead(valid(track)).track,track)
assert.throws(()=>validateLead({...valid('marque'),consent:false}))
assert.throws(()=>validateLead({...valid('marque'),phone:'abc0550000000'}))
assert.throws(()=>validateLead({...valid('marque'),answers:{}}))
assert.throws(()=>validateLead({...valid('studio'),date:'2099-02-31'}))
assert.throws(()=>validateLead({...valid('studio'),date:'2020-01-01'}))
assert.throws(()=>validateLead({...valid('marque'),website:'spam'}))
assert.throws(()=>validateLead({...valid('marque'),requestId:'arbitrary-key'}))
assert.throws(()=>validateLead({...valid('marque'),track:'invalid'}))
assert.throws(()=>validateLead({...valid('equipe'),channel:'E-mail',email:''}))
assert.equal(validateLead({...valid('equipe'),channel:'E-mail',phone:'',email:'qa@example.com'}).email,'qa@example.com')
assert.match(recommendation('studio',{formule:'Studio + tournage · 6 000 DA / h',duree:'2 heures'}).note,/12.*000/)
assert.match(recommendation('studio',{formule:'Prêt à publier · sur devis',duree:'2 heures'}).note,/définis avec toi/)
assert.equal(Object.keys(validateLead({...valid('marque'),attribution:{utm_source:'instagram',secret:'ignored'}}).attribution).join(','),'utm_source')
fs.rmSync(root,{recursive:true,force:true})
console.log('PASS: 17 checks — lead validation, consent, date, phone, options, attribution and studio pricing.')
